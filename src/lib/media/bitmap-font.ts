const FALLBACK = [0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f];

export function measureTextWidth(text: string, scale: number): number {
  const gap = scale;
  return text.length * (GLYPH_W * scale + gap);
}

export function drawText(
  rgba: Uint8Array,
  canvasW: number,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: [number, number, number],
): void {
  const [r, g, b] = color;
  let cursor = x;
  for (const ch of text) {
    const rows = FONT[ch] ?? FALLBACK;
    for (let row = 0; row < GLYPH_H; row++) {
      const bits = rows[row] ?? 0;
      for (let col = 0; col < GLYPH_W; col++) {
        if ((bits >> (GLYPH_W - 1 - col)) & 1) {
          for (let dy = 0; dy < scale; dy++) {
            for (let dx = 0; dx < scale; dx++) {
              const px = cursor + col * scale + dx;
              const py = y + row * scale + dy;
              if (px < 0 || py < 0 || px >= canvasW) continue;
              const i = (py * canvasW + px) * 4;
              if (i + 3 >= rgba.length) continue;
              rgba[i] = r;
              rgba[i + 1] = g;
              rgba[i + 2] = b;
              rgba[i + 3] = 255;
            }
          }
        }
      }
    }
    cursor += GLYPH_W * scale + scale;
  }
}

export function wrapText(
  text: string,
  maxWidthPx: number,
  scale: number,
): string[] {
  const words = text.replace(/\s+/g, " ").trim().split(" ");
  if (words.length === 0 || words[0] === "") return [];
  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    const trial = current ? `${current} ${word}` : word;
    if (measureTextWidth(trial, scale) <= maxWidthPx) {
      current = trial;
    } else {
      if (current) lines.push(current);
      current = word;
    }
  }
  if (current) lines.push(current);
  return lines;
}

